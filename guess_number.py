"""
猜数字小游戏
============

玩法：
    电脑随机想一个 1 到 100 之间的整数，
    玩家不停输入自己猜的数字，程序提示『大了』或『小了』，
    直到猜中为止，最后告诉玩家一共猜了几次。

运行：
    在命令行（cmd）里执行：python guess_number.py

作者：cgrhsdy
"""

import random  # 导入 random 模块，用它来生成随机数


# ============================================================
# 第 1 步：电脑先想好一个数字
# ============================================================
# random.randint(1, 100) 会随机返回一个 1~100 的整数（1 和 100 都能取到）
answer = random.randint(1, 100)

print("=" * 44)
print("            猜数字小游戏")
print("=" * 44)
print("我已经想好了一个 1 到 100 之间的整数。")
print('你每猜一次，我会告诉你大了还是小了。')
print("-" * 44)


# ============================================================
# 第 2 步：用 while 循环反复让玩家猜
# ============================================================
count = 0  # 计数器，用来记录玩家一共猜了几次

while True:  # True 就是"条件永远成立"，会一直循环，直到遇到 break 才结束
    text = input("请输入你猜的数字（1-100）：")

    # ---------- 2.1 先检查输入是不是合法的整数 ----------
    # input() 拿到的永远是字符串，所以要先判断它长得像不像整数
    if not text.strip().isdigit():
        print(">> 输入无效，请输入一个整数，例如 42")
        print()
        continue  # continue = 跳过本轮循环剩下的代码，直接回到开头再问一次

    guess = int(text)  # 确认是整数后，把字符串转成真正的整数
    count = count + 1  # 玩家猜了一次，计数加 1

    # ---------- 2.2 把玩家的猜测和答案比大小 ----------
    if guess > answer:
        print(">> 大了，往小一点猜")
        print()

    elif guess < answer:
        print(">> 小了，往大一点猜")
        print()

    else:
        # ---------- 2.3 既不大于也不小于，说明猜中了 ----------
        print()
        print("=" * 44)
        print(f"恭喜你，猜对了！答案就是 {answer}")
        print(f"你一共猜了 {count} 次。")
        print("=" * 44)
        break  # break = 跳出循环，程序结束
